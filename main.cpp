void rememberMessage(const std::string& text) {

    recentMessages.push_back(text);

    if (recentMessages.size() > MAX_MEMORY)
        recentMessages.pop_front();
}


// ==============================
// РАБОТА С СОСТОЯНИЕМ
// ==============================

void registerMessage(const std::string& text) {

    messageCount++;

    rememberMessage(text);

    lastMessageTime =
        std::chrono::steady_clock::now();

    // Каждые 20 сообщений бот слегка звереет.
    if (messageCount % 20 == 0) {

        madnessLevel++;

        if (madnessLevel > 10)
            madnessLevel = 10;
    }
}


void registerBugulma() {

    bugulmaCount++;

    madnessLevel += 2;

    if (madnessLevel > 20)
        madnessLevel = 20;
}


