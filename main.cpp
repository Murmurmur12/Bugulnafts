// ==============================

std::string getRandomFrom(
    const std::vector<std::string>& vec
    ) {

    if (vec.empty())
        return "";

    std::uniform_int_distribution<size_t> dist(
        0,
        vec.size() - 1
        );

    return vec[dist(rng)];
}


